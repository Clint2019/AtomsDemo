from __future__ import annotations
from types import TracebackType
from typing import Protocol, TypeVar
from atoms_demo.core.types import EntityId, Page, PageQuery, Scope

T = TypeVar("T")


class Repository(Protocol[T]):
    """TODO: owner-scoped aggregate repository; no client-selected table or raw SQL."""
    async def get(self, scope: Scope, entity_id: EntityId) -> T | None: ...
    async def list(self, scope: Scope, page: PageQuery) -> Page[T]: ...
    async def latest(self, scope: Scope) -> T | None: ...
    async def save(self, scope: Scope, entity: T, expected_revision: int | None) -> T: ...
    async def delete(self, scope: Scope, entity_id: EntityId, expected_revision: int) -> None: ...


class UnitOfWork(Protocol):
    async def __aenter__(self) -> UnitOfWork: ...
    async def __aexit__(self, exc_type: type[BaseException] | None, exc: BaseException | None, tb: TracebackType | None) -> bool | None: ...
    def repository(self, entity_type: type[T]) -> Repository[T]: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...
