from __future__ import annotations
from datetime import datetime
from typing import Protocol
from atoms_demo.core.types import BlobRef, EntityId, RequestContext, Scope, SecretRef
from atoms_demo.core.events import TaskEvent
from atoms_demo.ports.persistence import UnitOfWork


class Authorization(Protocol):
    async def require(self, ctx: RequestContext, action: str, resource_id: EntityId | None) -> None: ...


class BlobStore(Protocol):
    async def put(self, content: bytes, media_type: str) -> BlobRef: ...
    async def read(self, reference: BlobRef) -> bytes: ...
    async def delete(self, reference: BlobRef) -> None: ...


class AttachmentAccess(Protocol):
    async def exists(self, workspace_id: EntityId, project_id: EntityId, object_id: EntityId) -> bool: ...


class SecretStore(Protocol):
    async def put(self, scope: Scope, value: str) -> SecretRef: ...
    async def resolve(self, reference: SecretRef) -> str: ...
    async def revoke(self, reference: SecretRef) -> None: ...
    def fingerprint(self, value: str) -> str: ...


class EventStore(Protocol):
    async def append(self, event: TaskEvent) -> None: ...
    async def read(self, task_id: EntityId, after_sequence: int) -> tuple[TaskEvent, ...]: ...


class JobQueue(Protocol):
    async def enqueue(self, task_id: EntityId, idempotency_key: str) -> None: ...
    async def lease(self, worker_id: str) -> EntityId | None: ...
    async def acknowledge(self, task_id: EntityId, worker_id: str) -> None: ...
    async def heartbeat(self, task_id: EntityId, worker_id: str) -> None: ...


class CommitFence(Protocol):
    async def has_live_lease(self, uow: UnitOfWork, task_id: EntityId) -> bool: ...
    async def assert_owned_lease(self, uow: UnitOfWork, task_id: EntityId,
                                 lease_owner: str) -> None: ...
    async def assert_valid(self, uow: UnitOfWork, workspace_id: EntityId,
                           project_id: EntityId, task_id: EntityId,
                           version_id: EntityId, lease_owner: str) -> None: ...


class TaskMessageWriter(Protocol):
    """Persist a task-related conversation message in the task's transaction."""
    async def append(self, uow: UnitOfWork, scope: Scope, message_id: EntityId,
                     project_id: EntityId, task_id: EntityId, role: str,
                     content: str, previous_message_id: EntityId,
                     created_at: datetime) -> None: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdFactory(Protocol):
    def new(self) -> EntityId: ...


class UserDirectory(Protocol):
    """Read-only identity lookup used by workspace invitation rules."""
    async def email_for(self, user_id: EntityId) -> str | None: ...


class PlatformSessionLookup(Protocol):
    """Read whether a platform login session is still active."""
    async def actor_for(self, session_id: EntityId, now: datetime) -> EntityId | None: ...


class ProjectWorkspaceLookup(Protocol):
    async def workspace_for(self, project_id: EntityId) -> EntityId | None: ...


class PublicCatalogSource(Protocol):
    async def author_for(self, project_id: EntityId, version_id: EntityId) -> EntityId | None: ...
